"""Print the PgBouncer ``[databases]`` section for this gateway configuration.

Run it where the gateway's configuration file and environment are available,
for example in an API pod, and copy the output into ``pgbouncer.ini``:

    python -m src.db.runtime.pooler_config --host postgres.internal --dbname deltallm

Each alias sets the server deadlines of one database allocation with
``connect_query``. The gateway checks at startup that they apply, so a
stale ``pgbouncer.ini`` stops startup instead of running without deadlines.
"""

from __future__ import annotations

import argparse
import sys
from urllib.parse import urlsplit

from src.bootstrap.accounting_config import read_accounting_settings
from src.config import resolve_database_settings
from src.database_pooler import (
    POOLER_ALLOCATIONS,
    POOLER_SEARCH_PATH,
    pgbouncer_database_lines,
    require_pooler_schema,
)
from src.db.runtime.accounting_pool import accounting_session_settings
from src.db.runtime.allocation_config import DatabasePolicy, resolve_allocation_settings
from src.startup_config import StartupConfig


def _alias_template(pooler_url: str | None) -> str:
    if pooler_url is None:
        return "deltallm_{allocation}"
    return urlsplit(pooler_url).path.lstrip("/") or "deltallm_{allocation}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--host", required=True, help="PostgreSQL host that PgBouncer connects to")
    parser.add_argument("--port", type=int, default=5432, help="PostgreSQL port")
    parser.add_argument("--dbname", required=True, help="PostgreSQL database name")
    parser.add_argument(
        "--alias",
        help="Alias template with {allocation}. Default: the database name of "
        "DELTALLM_DATABASE_POOLER_URL, or deltallm_{allocation}",
    )
    args = parser.parse_args(argv)

    startup = StartupConfig.load()
    general, settings = startup.app_config.general_settings, startup.settings
    allocation = resolve_allocation_settings(general, settings)
    accounting = read_accounting_settings(general, settings)
    database = resolve_database_settings(startup.app_config, settings)
    statement_seconds = accounting.accounting_statement_timeout_ms / 1000
    direct_url = database.url if database is not None else "postgresql://localhost/deltallm"
    session = accounting_session_settings(
        direct_url,
        statement_seconds=statement_seconds,
        lock_seconds=min(allocation.db_lock_timeout_seconds, statement_seconds),
    )
    # Every alias sets the public schema: a server connection that PgBouncer
    # opens later must not fall back to another search_path.
    session_settings: dict[str, tuple[tuple[str, str], ...]] = {
        name: (POOLER_SEARCH_PATH,)
        + tuple(
            (setting, str(value))
            for setting, value in DatabasePolicy.build(allocation, name, 1).server_deadlines()
        )
        for name in POOLER_ALLOCATIONS
        if name != "accounting"
    }
    session_settings["accounting"] = (POOLER_SEARCH_PATH,) + tuple(
        (name, value)
        for name, value in session.items()
        if name not in {"application_name", "search_path"}
    )
    try:
        require_pooler_schema(direct_url)
        lines = pgbouncer_database_lines(
            alias_template=args.alias or _alias_template(settings.database_pooler_url),
            host=args.host,
            port=args.port,
            dbname=args.dbname,
            settings=session_settings,
        )
    except ValueError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    print(
        "; Generated by python -m src.db.runtime.pooler_config. Requires pool_mode = transaction."
    )
    print("[databases]")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
